export function useI18n() {
  const preferences = usePreferences()
  function t(text: string) {
    return preferences.values.language === 'en-US' ? (english[text] ?? text) : text
  }
  function libraryName(id: string, name: string) {
    return id === 'default' ? t('我的知识库') : name
  }
  return { t, preferences, libraryName }
}
