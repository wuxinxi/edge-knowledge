from collections.abc import AsyncIterator, Iterable
from typing import Protocol

from edge_knowledge.domain.backup import BackupSnapshot
from edge_knowledge.domain.folders import SourceFile
from edge_knowledge.domain.models import (
    Asset,
    Chunk,
    Document,
    Library,
    ModelCapabilities,
    OCRResult,
    PreparedImage,
    QueryPlan,
    SearchHit,
)
from edge_knowledge.domain.multimodal import (
    ArchivedRecord,
    ContextBudget,
    EmbeddingInput,
    InputAsset,
    MediaInfo,
)


class Embedder(Protocol):
    @property
    def ready(self) -> bool: ...
    @property
    def enable_images(self) -> bool: ...
    def documents(self, texts: list[str]) -> list[list[float]]: ...
    def query(self, text: str) -> list[float]: ...
    def image(self, content: bytes) -> list[float]: ...
    @property
    def loaded(self) -> bool: ...


class DocumentParser(Protocol):
    def parse(self, filename: str, content: bytes) -> str: ...


class KnowledgeRepository(Protocol):
    def lexical_candidates(
        self,
        library_id: str,
        embedding: list[float],
        terms: list[str],
        top_k: int,
        document_ids: list[str] | None = None,
    ) -> list[SearchHit]: ...

    def record(self, library_id: str, document_id: str) -> ArchivedRecord: ...
    def delete_many(self, library_id: str, document_ids: list[str]) -> None: ...
    def snapshot(self, library_id: str) -> list[ArchivedRecord]: ...
    def remove_library(self, library_id: str) -> None: ...
    def vectors(self, library_id: str) -> list[tuple[SearchHit, list[float]]]: ...
    def chunks(self, library_id: str, document_id: str) -> list[Chunk]: ...
    def libraries(self) -> list[Library]: ...
    def create_library(self, name: str) -> Library: ...
    def documents(self, library_id: str) -> list[Document]: ...
    def add(
        self,
        library_id: str,
        document: Document,
        chunks: list[Chunk],
        embeddings: list[list[float]],
    ) -> None: ...
    def delete(self, library_id: str, document_id: str) -> None: ...
    def search(
        self,
        library_id: str,
        embedding: list[float],
        top_k: int,
        document_ids: list[str] | None = None,
    ) -> list[SearchHit]: ...


class SettingsStore(Protocol):
    def read(self) -> dict: ...
    def update(self, changes: dict) -> dict: ...
    def api_key(self) -> str: ...


class Generator(Protocol):
    def capabilities(self, model: str) -> ModelCapabilities: ...
    def generate(self, plan: QueryPlan) -> AsyncIterator[str]: ...


class ImageProcessor(Protocol):
    def prepare(self, content: bytes) -> PreparedImage: ...
    def for_generation(self, content: bytes) -> Asset: ...


class OCR(Protocol):
    @property
    def available(self) -> bool: ...
    def recognize(self, content: bytes) -> OCRResult: ...


class AssetStore(Protocol):
    def snapshot(self, library_id: str, document_id: str) -> tuple[PreparedImage, OCRResult]: ...
    def put(
        self, library_id: str, document_id: str, image: PreparedImage, ocr: OCRResult
    ) -> None: ...
    def get(self, library_id: str, document_id: str, thumbnail: bool = False) -> Asset: ...
    def delete(self, library_id: str, document_id: str) -> None: ...


# Multimodal ports retain bytes and domain inputs, never paths, numpy or codec types.


class MultimodalEmbedder(Protocol):
    def encode_input(
        self, item: EmbeddingInput, task: str = "search", dimension: int = 768
    ) -> list[float]: ...
    def budget(self, item: EmbeddingInput, task: str = "search") -> ContextBudget: ...
    def split_text(self, text: str, task: str = "document") -> list[str]: ...


class MediaDecoder(Protocol):
    def probe(self, asset: InputAsset) -> MediaInfo: ...
    def segments(self, asset: InputAsset) -> Iterable[EmbeddingInput]: ...


class PayloadStore(Protocol):
    def put(self, library: str, document: str, text: str, assets: list[InputAsset]) -> None: ...
    def get(self, library: str, document: str) -> tuple[str, list[InputAsset]]: ...
    def delete(self, library: str, document: str) -> None: ...


class ArchiveStore(Protocol):
    def put(self, library: str, record: ArchivedRecord) -> None: ...
    def get(self, library: str, document: str) -> ArchivedRecord: ...
    def list(self, library: str) -> list[Document]: ...
    def delete(self, library: str, document: str) -> None: ...


class CredentialStore(Protocol):
    @property
    def backend_name(self) -> str: ...
    def get(self) -> str | None: ...
    def set(self, value: str) -> None: ...
    def delete(self) -> None: ...


class BackupCodec(Protocol):
    def encode(self, snapshot: "BackupSnapshot") -> bytes: ...
    def decode(self, data: bytes) -> "BackupSnapshot": ...


class SourceStore(Protocol):
    def lease(self, library: str, source: str) -> tuple[int, bool]: ...
    def activate(self, library: str, source: str) -> None: ...
    def suspend_library(self, library: str) -> None: ...
    def get(self, library: str, source: str, path: str) -> SourceFile | None: ...
    def files(self, library: str, source: str) -> list[SourceFile]: ...
    def put(self, library: str, source: str, entry: SourceFile) -> None: ...
    def remove(self, library: str, source: str, path: str) -> None: ...
